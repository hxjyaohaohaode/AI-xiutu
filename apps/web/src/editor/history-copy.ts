const lookup = new Map(labels.map((entry) => [entry[0], entry]));

export function historyText(label: string): string {
  const locale = getLocale();
  if (locale === 'zh-CN') {
    const values: Record<string, string> = {
      linear: '线性',
      'pchip-v1': '平滑（PCHIP）',
      radial: '径向',
      ellipse: '椭圆',
      rectangle: '矩形',
      diamond: '菱形',
      polygon: '多边形',
      brush: '笔刷',
      raster: '像素蒙版',
      'color-range': '色彩范围',
      compound: '组合选区',
      union: '并集',
      intersection: '交集',
      subtract: '相减',
      xor: '互斥',
      contain: '完整画幅',
      crop: '裁切画幅',
      push: '推移',
      pinch: '收缩',
      bulge: '膨胀',
      twirl: '旋转',
      paint: '绘制',
      erase: '擦除',
      clone: '克隆',
      add: '新增',
    };
    return values[label] ?? label;
  }
  const entry = lookup.get(label);
  if (entry) return entry[locale === 'en' ? 2 : 1];
  if (label.includes(' · ')) return label.split(' · ').map(historyText).join(' · ');
  const indexed = /^(笔画|曲线) (\d+|RGB|RED|GREEN|BLUE)$/.exec(label);
  if (indexed) return `${historyText(indexed[1]!)} ${indexed[2]}`;
  return t(label);
}
