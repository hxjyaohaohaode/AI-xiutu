export type MotionRole = keyof typeof motionRegistry;
export type MotionPhase = 'enter' | 'idle' | 'exit' | 'hidden';
export function motionProfile(
  role: MotionRole,
  width = typeof window === 'undefined' ? 1440 : window.innerWidth,
) {
  const p = motionRegistry[role];
  return width < 760 ? p.phone : width < 1120 ? p.tablet : p;
}
export const motionEntryDuration = (role: MotionRole) => {
  const p = motionProfile(role);
  return p.entryMs + p.delayMs + 90;
};
export const motionExitDuration = (role: MotionRole) => motionProfile(role).exitMs;
